import pandas as pd
import matplotlib.pyplot as plt
import seaborn as sns

tips_dataset = sns.load_dataset('tips')
tips_dataset.head()

sns.set_style('whitegrid')
# element to handle the overlapping columns
sns.histplot(x = tips_dataset.tip, hue = tips_dataset.day, element='step')
plt.show()

# displot --------> day with sex
sns.displot(x = tips_dataset.day, hue = tips_dataset.sex, multiple='dodge', shrink = 0.8 ,
             palette= 'Set1', hue_order = ['Female', 'Male'])
plt.show()

# ecdf plot --------> tip with time
sns.set_style('darkgrid')
sns.set(font_scale=1.25)
sns.ecdfplot(x = tips_dataset.tip, hue=tips_dataset.time, palette='summer', linewidth=3)
plt.show()

